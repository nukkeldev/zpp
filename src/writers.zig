// -- Constants -- //

const WRITER_BUFFER_SIZE = 32_768;

const log = std.log.scoped(.writers);

// -- Writers -- //

/// Context to be ingested and modified by each instruction write loop.
pub const Context = struct {
    fwd_decls: std.StringHashMap(usize),
    overload_map: std.StringHashMap(usize),
    ns_stack: std.array_list.Managed([]const u8),
    member_stack: std.array_list.Managed(*std.array_list.Managed(usize)),
    parent_stack: std.array_list.Managed(Parent),
    unwind_to_parent: bool = false,

    pub const Parent = struct {
        instr_idx: usize,
        /// `writer.end` where the writing started.
        writer_start: usize,
        inner: union(enum) {
            function,
            /// The amount of unnamed fields.
            @"struct": usize,
            @"enum",
            @"union",
            namespace,
            /// The size of the field in bits.
            bitfield: usize,
            // TODO: This is for typedefs and values with members; the members should be filtered
            // TODO: out beforehand.
            ignore_members,
            root,
        },
    };
};

pub const IRWriter = struct {
    formatFilename: FormatFilename,
    initContext: ?InitContext = null,
    writeInstruction: WriteInstruction,
    writeFilePrefix: ?WriteFilePrefix = null,
    writeFileSuffix: ?WriteFileSuffix = null,
    postProcessFile: ?PostProcessFile = null,
    checkFile: ?CheckFile = null,

    const FormatFilename = *const fn (std.mem.Allocator, []const u8) std.mem.Allocator.Error![:0]const u8;
    const InitContext = *const fn (std.mem.Allocator, *Context) anyerror!void;
    const WriteFilePrefix = *const fn (*const IR, *std.Io.Writer) anyerror!void;
    const WriteInstruction = *const fn (*const IR, usize, *Context, *std.Io.Writer) WriteInstructionError!void;
    const WriteFileSuffix = *const fn (*const IR, *std.Io.Writer) anyerror!void;
    const PostProcessFile = *const fn (std.mem.Allocator, []const u8) anyerror!void;
    const CheckFile = *const fn (std.mem.Allocator, [:0]const u8, anytype) anyerror!bool;

    pub const WriteInstructionError = error{
        Revert,
    } || std.mem.Allocator.Error || std.Io.Writer.Error;
};

