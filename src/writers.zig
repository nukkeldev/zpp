pub fn writeToFile(
    allocator: std.mem.Allocator,
    ir: *const IR,
    ir_writer: IRWriter,
    filename: []const u8,
) !void {
    var fz = tracy.FnZone.init(@src(), "writers.writeToFile");
    defer fz.end();

    const formatted_filename = try ir_writer.formatFilename(allocator, filename);

    var file = try std.fs.cwd().createFile(formatted_filename, .{});
    var buffer: [WRITER_BUFFER_SIZE]u8 = undefined;
    @memset(&buffer, 0);
    var writer = file.writer(&buffer);

    if (ir_writer.writeFilePrefix) |wfp| try wfp(ir, &writer.interface);

    var ctx: Context = .{
        .fwd_decls = .init(allocator),
        .overload_map = .init(allocator),
        .ns_stack = .init(allocator),
        .member_stack = .init(allocator),
        .parent_stack = .init(allocator),
    };
    if (ir_writer.initContext) |ic| try ic(allocator, &ctx);

    var i: usize = 0;
    while (i < ir.instrs.items.len) : (i += 1) {
        ir_writer.writeInstruction(ir, i, &ctx, &writer.interface) catch |e| switch (e) {
            error.Revert => {
                // Add reason for the reversion.
                log.err("Reverting '{s}' write.", .{ir.instrs.items[ctx.parent_stack.getLast().instr_idx].name});
                ctx.unwind_to_parent = true;
            },
            else => return e,
        };
    }

    if (ir_writer.writeFileSuffix) |wfs| try wfs(ir, &writer.interface);

    try writer.interface.flush();
    file.close();

    if (ir_writer.postProcessFile) |ppf| try ppf(allocator, formatted_filename);
}

pub fn checkFile(
    allocator: std.mem.Allocator,
    ir_writer: IRWriter,
    filename: []const u8,
    args: anytype,
) !void {
    var fz = tracy.FnZone.init(@src(), "writers.checkFile");
    defer fz.end();

    if (ir_writer.checkFile == null) {
        std.log.err("Nothing to check the file with for IRWriter!", .{});
        return;
    }

    const formatted_filename = try ir_writer.formatFilename(allocator, filename);

    const good = try ir_writer.checkFile.?(
        allocator,
        formatted_filename,
        args,
    );

    if (!good) {
        std.log.err("'{s}' failed checks!", .{formatted_filename});
    }
}
